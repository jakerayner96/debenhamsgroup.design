/* DG Group Design System — Virtual Stylist intro (2 Nov 2026, vto-prototype v2).
   The launch modal for Virtual Stylist (virtual try-on), on the DS .mdl: How it works (.howto, three numbered steps) · Photo tips (.ptips, 2 × 2) ·
   the 18+ consent row (DS checkbox .chk in .chk-row--lg + .vs-legal; a legal record, it never gates the buttons) · Take a photo (.bd pri) /
   Upload a photo (.bd sec) · the try-on note (.vs-note). Centred .mdl--md from 600px, the .mdl--up slide up on phones.
     DG_vsIntro.html(o)   → the .mdl only (catalogue, Figma)       o = {fascia:'Debenhams', desk:bool, left:5|n, consent:bool}
     DG_vsIntro.layer(o)  → scrim + .mdl in a fixed .vs-layer (pages)
     DG_vsIntro.wire(root, {onCamera, onUpload, onClose, onConsent}) → binds the X, scrim, consent row and the two buttons
   Copy is instructional; no emojis, no em dashes. */
(function(root){
  const esc=s=>String(s==null?'':s).replace(/[&<>"]/g,m=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[m]));
  const STEPS=[['add-photo','Add a full-length photo of you'],['ai','We style you in this piece'],['hanger','Check the look, then pick your size']];
  const TIPS=[['light','Bright, even light'],['dress','Head to toe in frame'],['face','Face the camera'],['plain','Plain background']];
  const note=n=>(n==null||n>=5?'Max 5 try-ons per day.':n+' try-on'+(n===1?'':'s')+' left today.')+' Images are generated by AI';
  function html(o){o=o||{};
    return `<div class="mdl ${o.desk?'mdl--md':'mdl--up'} vs-intro" role="dialog" aria-modal="true" aria-labelledby="vs-intro-t">
      <div class="modal-hd"><span class="mt" id="vs-intro-t">Virtual Stylist</span><button class="modal-x" data-vs-close aria-label="Close"></button></div>
      <div class="mdl-bd">
        <section class="vs-sec"><h3 class="vs-sec-h">How it works</h3>
          <ol class="howto">${STEPS.map(([i,t],n)=>`<li><span class="n">${n+1}</span><i class="vsi vsi--${i}" aria-hidden="true"></i><span>${t}</span></li>`).join('')}</ol></section>
        <section class="vs-sec"><h3 class="vs-sec-h">For the best result</h3>
          <ul class="ptips">${TIPS.map(([i,t])=>`<li><i class="vsi vsi--${i}" aria-hidden="true"></i><span>${t}</span></li>`).join('')}</ul></section>
        <div class="chk-row chk-row--lg vs-consent" data-vs-consent role="checkbox" aria-checked="${o.consent?'true':'false'}" tabindex="0">
          <button class="chk${o.consent?' on':''}" tabindex="-1" aria-hidden="true"></button>
          <p class="vs-legal">I'm 18 or over and consent to my photo being processed by ${esc(o.fascia||'Debenhams')} and its AI providers to create my virtual try-on. I accept the <a href="#" data-vs-link>Terms &amp; Conditions</a> and <a href="#" data-vs-link>Privacy Policy</a>.</p>
        </div>
      </div>
      <div class="mdl-ft">
        <div class="vs-ctas"><button class="bd pri" data-vs-camera>Take a photo</button><button class="bd sec" data-vs-upload>Upload a photo</button></div>
        <p class="vs-note" data-vs-note>${note(o.left)}</p>
      </div>
    </div>`}
  const layer=o=>`<div class="vs-layer${o&&o.desk?'':' vs-layer--up'}" data-vs-intro><div class="mdl-scrim" data-vs-close></div>${html(o)}</div>`;
  function wire(el,h){h=h||{};if(!el)return;
    el.querySelectorAll('[data-vs-close]').forEach(b=>b.onclick=e=>{e.preventDefault();h.onClose&&h.onClose()});
    el.querySelectorAll('[data-vs-link]').forEach(a=>a.onclick=e=>{e.preventDefault();e.stopPropagation()});
    const row=el.querySelector('[data-vs-consent]');
    if(row){const t=()=>{const on=row.getAttribute('aria-checked')!=='true';row.setAttribute('aria-checked',on);row.querySelector('.chk').classList.toggle('on',on);h.onConsent&&h.onConsent(on)};
      row.onclick=e=>{if(e.target.closest('a'))return;t()};row.onkeydown=e=>{if(e.key===' '||e.key==='Enter'){e.preventDefault();t()}}}
    const c=el.querySelector('[data-vs-camera]'),u=el.querySelector('[data-vs-upload]');
    if(c)c.onclick=()=>h.onCamera&&h.onCamera();if(u)u.onclick=()=>h.onUpload&&h.onUpload()}
  root.DG_vsIntro={html,layer,wire,note,STEPS,TIPS};
})(typeof window!=='undefined'?window:globalThis);
