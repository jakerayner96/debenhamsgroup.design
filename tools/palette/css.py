import json,sys,re
B=json.load(open('tools/palette/palette.json'))
def css(n): return '--'+re.sub(r'[^a-z0-9]+','-',re.sub(r'\s*\((man|plt)\)','',n.lower()).replace('+',' plus')).strip('-')
def decl(v):
    d={}
    for grp in ('primary','accents','shades','extended','mono'):
        for k,x in v[grp].items(): d[css(k)]=x
    return d
base=decl(B['debenhams'])
out=['/* Layer 0: COLOUR PALETTE — the Figma "DG Group Design System" collection (Debenhams Design System aIHmkCaTy9c5EWOxAGw0So), same names:',
 '   Primary + CTA (Action) · Shades (Neutral, Neutral Pressed, Light 4 → 1, Primary, Dark 1 → 3, Primary Dark) · brand accents · Extended (Red … System Cursor, Pay+) ·',
 '   Mono (White, Background White, Grey 05 / 1 / 2 / 25 / 3 / 4 / 5 / 6, Soft Black, Black). One mode per brand = one block per brand below.',
 '   Values = latest sign-off (Aug 2026 brand colour pages; one red #C90000 for every brand, 23 Oct). Source: tools/tools/palette/palette.json (28 Oct 2026).',
 '   Primitives only: components use the semantic tokens (Layer 1 / 2), which are not re-pointed here. */',
 ':root{'+';'.join(f'{k}:{x}' for k,x in base.items())+'}']
for key,v in B.items():
    if key=='debenhams': continue
    d=decl(v); diff={k:x for k,x in d.items() if base.get(k)!=x}
    out.append(f'[data-brand="{key}"]{{'+';'.join(f'{k}:{x}' for k,x in diff.items())+f'}} /* {v["name"]} — {v["src"]} */')
blk='\n'.join(out)+'\n'
p='assets/ds/tokens.css'; s=open(p).read()
s=re.sub(r'/\* Layer 0: COLOUR PALETTE.*?\n(?=/\* Layer 2: per-fascia overrides)','',s,flags=re.S)
a='/* Layer 2: per-fascia overrides.'
assert s.count(a)==1; s=s.replace(a,blk+a,1); open(p,'w').write(s)
print(blk[:1500]); print(sorted(base))
# assets/ds/palette.js — the same palette for the site's Colour page (and any page that needs the named swatches)
js='/* DG Group colour palette — generated by tools/palette/css.py from tools/palette/palette.json. Do not edit by hand.\n   Same names and values as the Figma "DG Group Design System" collection; CSS custom properties in tokens.css Layer 0. */\n'
js+='window.DG_PALETTE='+json.dumps(B,ensure_ascii=False)+';\nwindow.DG_PALETTE_CSS=function(n){return '+json.dumps({k:css(k) for v in B.values() for g in ('primary','accents','shades','extended','mono') for k in v[g]})+'[n]};\n'
open('assets/ds/palette.js','w').write(js)
